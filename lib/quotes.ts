/** 로그인 시각(같은 로그인 동안은 같은 값)으로 글귀 번호를 정한다 */
export function quoteIndexFor(seed: string): number {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) h = Math.imul(h ^ seed.charCodeAt(i), 16777619);
  return Math.abs(h) % QUOTES.length;
}
