export function signOf(month: number, day: number) {
  let found = SIGNS[0];
  for (const s of SIGNS.slice(1)) if (month > s[2] || (month === s[2] && day >= s[3])) found = s;
  if (month === 12 && day >= 22) found = SIGNS[0];
  return { name: found[0], symbol: found[1] };
}

