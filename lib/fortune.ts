// ── 씨앗으로 고르기 ──
function hash(s: string) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}
function rng(seed: string) {
  let a = hash(seed);
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const pick = <T,>(r: () => number, xs: readonly T[]) => xs[Math.floor(r() * xs.length)];
/** 별점 1~5 (대체로 3~4가 많게) */
const stars = (r: () => number) => {
  const x = r();
  return x < 0.07 ? 1 : x < 0.22 ? 2 : x < 0.55 ? 3 : x < 0.87 ? 4 : 5;
};
const levelOf = (s: number): Level => (s <= 2 ? 0 : s === 3 ? 1 : 2);

export type Fortune = {
  date: string;
  animal: { name: string; emoji: string };
  sign: { name: string; symbol: string };
  total: { stars: number; text: string };
  categories: { key: "love" | "money" | "work" | "health"; label: string; stars: number; text: string }[];
  lucky: { color: { name: string; hex: string }; number: number; direction: string; item: string };
  advice: string;
};

const LABELS = { love: "애정", money: "재물", work: "일·학업", health: "건강" } as const;

/** birth: YYYY-MM-DD, today: YYYY-MM-DD (서울 기준) */
export function fortuneFor(birth: string, today: string): Fortune {
  const [y, m, d] = birth.split("-").map(Number);
  const r = rng(`${birth}|${today}`);
  const totalStars = stars(r);
  const categories = (["love", "money", "work", "health"] as const).map((key) => {
    const s = stars(r);
    return { key, label: LABELS[key], stars: s, text: pick(r, CATEGORY[key][levelOf(s)]) };
  });
  const color = pick(r, COLORS);
  return {
    date: today,
    animal: animalOf(y),
    sign: signOf(m, d),
    total: { stars: totalStars, text: pick(r, OPEN) },
    categories,
    lucky: { color: { name: color[0], hex: color[1] }, number: 1 + Math.floor(r() * 45), direction: pick(r, DIRECTIONS), item: pick(r, ITEMS) },
    advice: pick(r, ADVICE),
  };
}

/** 생년월일 형식·범위 검사 (1900년 이후 ~ 오늘 이전) */
export function validBirth(v: string, today: string) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(v)) return false;
  const t = Date.parse(`${v}T00:00:00Z`);
  return !Number.isNaN(t) && v >= "1900-01-01" && v <= today && new Date(t).toISOString().slice(0, 10) === v;
}
